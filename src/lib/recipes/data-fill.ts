import type { ChapterId, Difficulty, Recipe } from './types';

/** Chapter fill toward ~15 recipes each + Tips wisdom + Jia's Favorites. */

type Tup = [number | null, string, string, string?];
type St = string | [string, number];

interface Mini {
  id: string;
  chapter: ChapterId;
  title: string;
  tagline: string;
  story: string;
  tasteLike: string;
  texture: string;
  cuisine: string;
  difficulty: Difficulty;
  spice?: number;
  allergens?: string[];
  prep: number;
  cook: number;
  servings: number;
  cal: number;
  protein: number;
  carbs: number;
  fat: number;
  tags: string[];
  ing: Tup[];
  steps: St[];
  tips?: string[];
  related?: string[];
  serveWith?: string[];
  seed: number;
}

function r(x: Mini): Recipe {
  return {
    id: x.id,
    chapter: x.chapter,
    title: x.title,
    tagline: x.tagline,
    story: x.story,
    tasteLike: x.tasteLike,
    texture: x.texture,
    cuisine: x.cuisine,
    difficulty: x.difficulty,
    spiceLevel: x.spice ?? 0,
    allergens: x.allergens ?? [],
    prepMin: x.prep,
    cookMin: x.cook,
    servings: x.servings,
    nutrition: {
      calories: x.cal,
      protein: x.protein,
      carbs: x.carbs,
      fat: x.fat,
      fiber: 2,
      sugar: 4,
    },
    tags: x.tags,
    ingredients: [{ items: x.ing.map(([q, u, it, n]) => ({ quantity: q, unit: u, item: it, note: n })) }],
    steps: x.steps.map((s) => (Array.isArray(s) ? { instruction: s[0], durationSec: s[1] } : { instruction: s })),
    tips: x.tips,
    related: x.related,
    serveWith: x.serveWith,
    heroSeed: x.seed,
  };
}

