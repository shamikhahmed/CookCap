def load_existing_ids() -> set[str]:
    ids: set[str] = set()
    for rel in (
        "src/lib/recipes/data.ts",
        "src/lib/recipes/data-extra.ts",
        "src/lib/recipes/data-fill.ts",
        # data-foodfusion.ts omitted — regenerated by this script
    ):
        p = ROOT / rel
        if not p.exists():
            continue
        ids.update(re.findall(r"\bid:\s*'([^']+)'", p.read_text(encoding="utf-8")))
    return ids


def http_get(url: str, retries: int = 3) -> tuple[bytes, dict[str, str]]:
    last: Exception | None = None
    for i in range(retries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
            with urllib.request.urlopen(req, timeout=90) as r:
                headers = {k.lower(): v for k, v in r.headers.items()}
                return r.read(), headers
        except Exception as e:  # noqa: BLE001
            last = e
            time.sleep(1.5 * (i + 1))
    raise RuntimeError(f"GET failed {url}: {last}")


def strip_tags(html: str) -> str:
    t = re.sub(r"<br\s*/?>", "\n", html, flags=re.I)
    t = re.sub(r"</p>", "\n", t, flags=re.I)
    t = re.sub(r"<[^>]+>", "", t)
    return unescape(re.sub(r"\s+", " ", t)).strip()



JUNK_STEP = re.compile(
    r"food fusion|sign up|login|don.?t have an account|already an account|"
    r"happy\s*cooking|redefining|digital food|subscribe|youtube|facebook|"
    r"follow us|#HappyCooking|video portal|talk of the town|eating out habits|"
    r"share your experience|comment below|recipe in english and urdu|"
    r"pakistan.?s first digital|flavorsome treat|next talk of the town",
    re.I,
)
URDU_TOKENS = re.compile(
    r"\b(mein|ker|dein|lein|aur|per|tak|janay|phir|dal|karein|"
    r"rakh|ho\s+jay|mix\s+ker|add\s+ker|side\s+per|ubal|pheela|"
    r"laga|tayyar|kliya|tarhan|ache)\b",
    re.I,
)


def is_branding_junk(text: str) -> bool:
    """Promo / login / site chrome — never keep. Roman Urdu OK."""
    t = text.strip()
    if not t:
        return True
    if JUNK_STEP.search(t):
        return True
    # Long marketing paragraphs (English promo)
    if len(t) > 320 and not URDU_TOKENS.search(t):
        return True
    return False


def is_section_heading(text: str) -> bool:
    t = text.strip().lower().rstrip(":")
    if len(t) < 2:
        return True
    if t in ("directions", "method", "ingredients", "ajza", "tariqa", "tarika"):
        return True
    if t.startswith("directions") or t.startswith("method") or t.startswith("ingredients") or t.startswith("ajza"):
        return True
    return False


def is_roman_urdu(text: str) -> bool:
    return len(URDU_TOKENS.findall(text)) >= 2


def extract_lang_block(html: str, cls: str) -> str:
    parts = re.split(rf'class="[^"]*{re.escape(cls)}[^"]*"', html, flags=re.I)
    if len(parts) < 2:
        return ""
    chunk = parts[1]
    chunk = re.split(
        r'class="[^"]*(?:urdu-detail-ff|english-detail-ff|related|ff-brand|recipe-detail-sidebar)',
        chunk,
        maxsplit=1,
        flags=re.I,
    )[0]
    return chunk


def paras_from(html_chunk: str) -> list[str]:
    out: list[str] = []
    for p in re.findall(r"<p[^>]*>(.*?)</p>", html_chunk, re.S | re.I):
        t = strip_tags(p)
        if not t:
            continue
        if is_section_heading(t):
            continue
        if is_branding_junk(t):
            break  # real promo/login — stop
        if len(t) < 12:
            continue
        if out and out[-1].lower() == t.lower():
            continue
        out.append(t)
    return out


def pair_steps(english: list[str], urdu: list[str]) -> list[dict]:
    """English instruction + Roman Urdu tip when lengths align; else append leftover."""
    steps: list[dict] = []
    n = max(len(english), len(urdu))
    for i in range(n):
        en = english[i] if i < len(english) else None
        ur = urdu[i] if i < len(urdu) else None
        if en and ur:
            steps.append({"instruction": en, "romanUrdu": ur})
        elif en:
            steps.append({"instruction": en, "romanUrdu": None})
        elif ur:
            steps.append({"instruction": ur, "romanUrdu": None})
    return steps


def clean_steps(steps: list) -> list:
    """Accept str list (legacy) or {instruction, romanUrdu} list."""
    out = []
    for s in steps:
        if isinstance(s, dict):
            en = (s.get("instruction") or "").strip()
            ur = (s.get("romanUrdu") or s.get("tip") or "").strip() or None
            if en and is_branding_junk(en):
                break
            if ur and is_branding_junk(ur):
                ur = None
            if not en:
                continue
            out.append({"instruction": en, "romanUrdu": ur})
        else:
            t = str(s).strip()
            if is_branding_junk(t):
                break
            out.append({"instruction": t, "romanUrdu": None})
    return out




def slug_id(slug: str) -> str:
    s = slug.lower().strip()
    s = re.sub(r"-recipe(-by-food-fusion)?$", "", s)
    s = re.sub(r"[^a-z0-9-]+", "-", s)
    s = re.sub(r"-{2,}", "-", s).strip("-")
    if not s:
        s = "ff-recipe"
    if len(s) > 56:
        s = s[:56].rstrip("-")
    return f"ff-{s}"


def is_junk_row(row: dict) -> bool:
    slug = (row.get("slug") or "").lower()
    title = (row.get("title") or "").lower()
    rid = (row.get("id") or "").lower()
    if "trash" in slug or "trash" in rid or title.startswith("trashed"):
        return True
    if rid.startswith("ff-trashed") or "trashed-" in slug:
        return True
    return False


def map_chapter(class_list: list[str], title: str) -> str:
    blob = " ".join(class_list + [title]).lower()
    scores: Counter[str] = Counter()
    for chapter, keys in CHAPTER_RULES:
        for k in keys:
            if k in blob:
                scores[chapter] += 1
    if scores:
        return scores.most_common(1)[0][0]
    return "meals"


