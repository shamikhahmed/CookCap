def reparse_body_quantities(body: dict) -> dict:
    groups = []
    for g in body.get("ingredientGroups") or []:
        items = []
        for it in g.get("items") or []:
            raw = it.get("raw") or it.get("item") or ""
            qty, unit, item, note = parse_qty(raw)
            items.append({"quantity": qty, "unit": unit, "item": item, "note": note, "raw": raw})
        if items:
            groups.append({"heading": g.get("heading"), "items": items})
    return {**body, "ingredientGroups": groups}


def pick_curated(catalog: list[dict], bodies: dict[str, dict], n: int = 72) -> list[dict]:
    existing = load_existing_ids()
    title_hit = {re.sub(r"[^a-z0-9]+", "", x.lower()) for x in existing}

    scored: list[tuple[int, dict]] = []
    for row in catalog:
        if is_junk_row(row):
            continue
        body = bodies.get(row["id"])
        if not body or is_junk_row(body):
            continue
        body = reparse_body_quantities(body)
        bodies[row["id"]] = body
        n_ing = sum(len(g["items"]) for g in body.get("ingredientGroups") or [])
        clean = clean_steps(list(body.get("steps") or []))
        body = {**body, "steps": clean}
        bodies[row["id"]] = body
        n_steps = len(clean)
        if n_ing < 3 or n_ing > 60 or n_steps < 3:
            continue
        if row["id"] in existing:
            continue
        tnorm = re.sub(r"[^a-z0-9]+", "", row["title"].lower())
        if tnorm in title_hit:
            continue
        parsed_qty = sum(1 for g in body["ingredientGroups"] for it in g["items"] if it["quantity"] is not None)
        score = 0
        score += min(n_ing, 20) + min(n_steps, 15) + min(parsed_qty, 15)
        if row.get("imageUrl"):
            score += 10
        if row["chapter"] == "pakistani":
            score += 8
        elif row["chapter"] in ("desserts", "breads", "snacks", "coffee"):
            score += 5
        blob = (row["title"] + " " + row["slug"]).lower()
        for kw in ("biryani", "karahi", "nihari", "haleem", "pulao", "qorma", "korma", "tikka", "naan", "paratha", "chai", "halwa", "kheer", "gulab"):
            if kw in blob:
                score += 6
        scored.append((score, body))

    scored.sort(key=lambda x: (-x[0], x[1]["title"]))
    # chapter balance
    picked: list[dict] = []
    per_ch: Counter[str] = Counter()
    for score, body in scored:
        ch = body["chapter"]
        if per_ch[ch] >= max(6, n // 8) and ch != "pakistani":
            continue
        if per_ch[ch] >= 18:
            continue
        picked.append(body)
        per_ch[ch] += 1
        if len(picked) >= n:
            break
    return picked


def ts_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", " ")


def qty_ts(q: float | None) -> str:
    if q is None:
        return "null"
    if abs(q - round(q)) < 1e-9:
        return str(int(round(q)))
    return str(round(q, 2))


def emit_typescript(curated: list[dict], path: Path) -> None:
    """Emit Recipe[] — English + Roman Urdu method, Jia-voice stories, zero FoodFusion branding in UI."""
    lines: list[str] = [
        "import type { Recipe } from './types';",
        "",
        "/**",
        " * Adapted kitchen cards (English method cleaned from public FoodFusion pages).",
        " * Not a copy-paste dump — promo/login/Urdu mirrors stripped. Private heirloom use.",
        " * Regen: python3 scripts/scrape-foodfusion.py --curate 64 --emit-ts",
        " */",
        "",
        "function seed(id: string): number {",
        "  let h = 0;",
        "  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;",
        "  return h % 10000;",
        "}",
        "",
        "export const FOODFUSION_RECIPES: Recipe[] = [",
    ]

    for rec in curated:
        groups = rec.get("ingredientGroups") or []
        steps = clean_steps(list(rec.get("steps") or []))
        if len(steps) < 3:
            continue
        # nutrition placeholders (unknown) — low confidence zeros avoided; modest defaults
        prep = 20
        cook = 40
        servings = 4
        # crude allergen guess
        blob = " ".join(
            i["item"] for g in groups for i in g["items"]
        ).lower()
        allergens: list[str] = []
        if any(x in blob for x in ("milk", "cream", "butter", "yogurt", "cheese", "ghee")):
            allergens.append("dairy")
        if any(x in blob for x in ("flour", "atta", "bread", "maida", "pasta")):
            allergens.append("gluten")
        if "egg" in blob:
            allergens.append("egg")
        if any(x in blob for x in ("almond", "cashew", "pistachio", "walnut", "peanut", "nut")):
            allergens.append("nuts")

        spice = 2 if rec["chapter"] == "pakistani" else 1
        if any(x in blob for x in ("chili", "chilli", "mirch", "pepper")):
            spice = min(5, spice + 1)

        tagline = (rec.get("ogDescription") or rec.get("excerpt") or f"{rec['title']} — adapted for our kitchen.").strip()
        tagline = re.sub(r"#HappyCooking\S*", "", tagline, flags=re.I).strip()
        tagline = re.sub(r"Food Fusion", "home kitchen", tagline, flags=re.I).strip()
        if len(tagline) > 110:
            tagline = tagline[:107] + "…"
        if len(tagline) < 12:
            tagline = f"{rec['title']} — adapted for our kitchen."
        story = (
            f"A kitchen card we adapted for the book — {rec['title']}. "
            f"Cook it once, then scribble your own timings in the notes."
        )

        lines.append("  {")
        lines.append(f"    id: '{rec['id']}',")
        lines.append(f"    chapter: '{rec['chapter']}',")
        lines.append(f"    title: '{ts_escape(rec['title'])}',")
        lines.append(f"    tagline: '{ts_escape(tagline)}',")
        lines.append(f"    story: '{ts_escape(story)}',")
        lines.append(f"    cuisine: 'Pakistani',")
        lines.append(f"    difficulty: 'medium',")
        lines.append(f"    spiceLevel: {spice},")
        lines.append(f"    allergens: {json.dumps(allergens)},")
        lines.append(f"    prepMin: {prep},")
        lines.append(f"    cookMin: {cook},")
        lines.append(f"    servings: {servings},")
        lines.append(
            "    nutrition: { calories: 450, protein: 18, carbs: 40, fat: 22, fiber: 3, sugar: 6 },  // estimate — not lab-tested"
        )
        lines.append(f"    tags: ['family', 'roman-urdu', '{rec['chapter']}'],")
        lines.append("    ingredients: [")
        for g in groups:
            lines.append("      {")
            if g.get("heading"):
                lines.append(f"        heading: '{ts_escape(g['heading'])}',")
            lines.append("        items: [")
            for it in g["items"]:
                note = f", note: '{ts_escape(it['note'])}'" if it.get("note") else ""
                lines.append(
                    f"          {{ quantity: {qty_ts(it['quantity'])}, unit: '{ts_escape(it['unit'])}', item: '{ts_escape(it['item'])}'{note} }},"
                )
            lines.append("        ],")
            lines.append("      },")
        lines.append("    ],")
        lines.append("    steps: [")
        for st in steps:
            if isinstance(st, dict):
                en = st.get("instruction") or ""
                ur = st.get("romanUrdu") or ""
            else:
                en, ur = str(st), ""
            if ur:
                lines.append(
                    f"      {{ instruction: '{ts_escape(en)}', tip: '{ts_escape(ur)}' }},"
                )
            else:
                lines.append(f"      {{ instruction: '{ts_escape(en)}' }},")
        lines.append("    ],")
        lines.append(
            "    tips: ['Taste as you go — every stove runs different.', 'Swap the hero for a family photo when you cook this.'],"
        )
        lines.append(f"    heroSeed: seed('{rec['id']}'),")
        lines.append("  },")

    lines.append("];")
    lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(curated)} recipes)")


def download_images(curated: list[dict]) -> None:
    img_dir = OUT / "images"
    img_dir.mkdir(parents=True, exist_ok=True)
    pub = ROOT / "public" / "recipes"
    pub.mkdir(parents=True, exist_ok=True)
    # use node+sharp via small helper
    jobs = []
    for rec in curated:
        url = rec.get("ogImage") or rec.get("imageUrl")
        if not url:
            continue
        # strip query for extension guess
        jobs.append({"id": rec["id"], "url": url})
    manifest = OUT / "image-jobs.json"
    manifest.write_text(json.dumps(jobs, indent=2), encoding="utf-8")
    print(f"image jobs: {len(jobs)} → {manifest}")
    # invoke node helper
    helper = ROOT / "scripts" / "fetch-foodfusion-images.mjs"
    if helper.exists():
        import subprocess

        subprocess.check_call(["node", str(helper)], cwd=str(ROOT))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force-catalog", action="store_true")
    ap.add_argument("--bodies", default="0", help="N | all")
    ap.add_argument("--curate", type=int, default=72)
    ap.add_argument("--download-images", action="store_true")
    ap.add_argument("--emit-ts", action="store_true")
    args = ap.parse_args()

    catalog = fetch_catalog(force=args.force_catalog)
    write_index(catalog)

    limit: int | None
    if args.bodies == "all":
        limit = None
    elif args.bodies == "0":
        limit = 0
    else:
        limit = int(args.bodies)

    bodies: dict[str, dict] = {}
    if limit != 0:
        bodies = fetch_bodies(catalog, limit)

    # load any existing bodies for curate
    bodies_dir = OUT / "recipes"
    if bodies_dir.exists():
        for p in bodies_dir.glob("*.json"):
            bodies.setdefault(p.stem, json.loads(p.read_text(encoding="utf-8")))

    curated = pick_curated(catalog, bodies, n=args.curate) if bodies else []
    if curated:
        (OUT / "curated.json").write_text(json.dumps(curated, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"curated {len(curated)}")
        ch = Counter(r["chapter"] for r in curated)
        print("  by chapter:", dict(ch))

    if args.emit_ts and curated:
        emit_typescript(curated, ROOT / "src" / "lib" / "recipes" / "data-foodfusion.ts")

    if args.download_images and curated:
        download_images(curated)

    print("done →", OUT)


if __name__ == "__main__":
    main()
