def _parse_num_token(tok: str) -> float | None:
    tok = tok.strip()
    if tok in FRAC:
        return FRAC[tok]
    m = re.match(r"^(\d+)\s*([½¼¾⅓⅔⅛⅜⅝⅞])$", tok)
    if m:
        return float(m.group(1)) + FRAC[m.group(2)]
    m = re.match(r"^(\d+(?:\.\d+)?)$", tok)
    if m:
        return float(m.group(1))
    return None


def parse_qty(raw: str) -> tuple[float | None, str, str, str | None]:
    """Parse 'Yogurt ½ cup' or '½ cup yogurt' → (qty, unit, item, note)."""
    text = unescape(raw).strip().replace("\u00a0", " ")
    note = None
    work = re.sub(r"(\d+)\s*-\s*\d+", r"\1", text)
    work = re.sub(r"(\d+)\s*&\s*([½¼¾⅓⅔⅛⅜⅝⅞])", lambda m: str(float(m.group(1)) + FRAC[m.group(2)]), work)
    work = re.sub(r"(\d+)\s*&\s*(\d+(?:/\d+)?)", r"\1", work)  # odd markup fallback
    qty: float | None = None
    unit = ""
    item = work

    trail = re.search(
        rf"^(?P<item>.+?)\s+(?P<qty>\d+\s*[½¼¾⅓⅔⅛⅜⅝⅞]|[½¼¾⅓⅔⅛⅜⅝⅞]|\d+(?:\.\d+)?)\s*(?P<unit>{UNIT_ALT})?\b\.?\s*(?P<tail>.*)$",
        work,
        re.I,
    )
    lead = re.match(
        rf"^(?P<qty>\d+\s*[½¼¾⅓⅔⅛⅜⅝⅞]|[½¼¾⅓⅔⅛⅜⅝⅞]|\d+(?:\.\d+)?)\s*(?P<unit>{UNIT_ALT})?\b\.?\s*(?P<item>.+)$",
        work,
        re.I,
    )
    use_trail = bool(trail) and bool(
        re.search(r"[A-Za-z\u0600-\u06FF)]\s+\d|[A-Za-z\u0600-\u06FF)]\s+[½¼¾⅓⅔⅛⅜⅝⅞]", work)
    )
    chosen = trail if use_trail else (lead or trail)
    if chosen:
        qty = _parse_num_token(chosen.group("qty"))
        unit_raw = (chosen.group("unit") or "").lower().strip()
        unit = UNIT_NORM.get(unit_raw, unit_raw)
        item = chosen.group("item").strip()
        if "tail" in chosen.groupdict() and chosen.group("tail"):
            tail = chosen.group("tail").strip()
            if tail and not note:
                note = tail
    if qty is None and not unit:
        item = text
    return qty, unit, item, note


def parse_body(html: str) -> dict:
    # Prefer recipe-step-direction-detail block
    block = ""
    m = re.search(
        r'id="recipe-step-direction-detail"[^>]*>(.*?)(?:id="recipe-|</article>|class="related)',
        html,
        re.S | re.I,
    )
    if m:
        block = m.group(1)
    else:
        block = html

    groups: list[dict] = []
    # Split by h4 section headings inside Ingredients area
    ing_start = re.search(r"Ingredients\s*:</", block, re.I)
    dir_start = re.search(r"(?:Directions|Method|Steps)\s*:</", block, re.I)

    ing_html = ""
    dir_html = ""
    if ing_start and dir_start and dir_start.start() > ing_start.start():
        ing_html = block[ing_start.start() : dir_start.start()]
        dir_html = block[dir_start.start() :]
    elif ing_start:
        ing_html = block[ing_start.start() :]
    else:
        # fallback: all ul.am-ing
        ing_html = block
        dir_html = block

    # ingredient groups
    parts = re.split(r"<h4[^>]*>", ing_html, flags=re.I)
    for part in parts:
        if not part.strip():
            continue
        hm = re.match(r"([^<]+)</h4>(.*)$", part, re.S | re.I)
        if hm:
            heading = strip_tags(hm.group(1)).rstrip(":")
            body = hm.group(2)
        else:
            heading = None
            body = part
        items = []
        # Prefer FoodFusion ingredient lists; fall back to bare <li>
        lis = re.findall(r'<ul[^>]*class="[^"]*am-ing[^"]*"[^>]*>(.*?)</ul>', body, re.S | re.I)
        li_htmls: list[str] = []
        if lis:
            for ul in lis:
                li_htmls.extend(re.findall(r"<li[^>]*>(.*?)</li>", ul, re.S | re.I))
        else:
            li_htmls = re.findall(r"<li[^>]*>(.*?)</li>", body, re.S | re.I)
        for li in li_htmls:
            raw = strip_tags(li)
            if not raw or len(raw) < 2:
                continue
            if raw.lower().startswith("http") or "food fusion" in raw.lower():
                continue
            qty, unit, item, note = parse_qty(raw)
            items.append(
                {
                    "quantity": qty,
                    "unit": unit,
                    "item": item,
                    "note": note,
                    "raw": raw,
                }
            )
        if items:
            groups.append({"heading": heading, "items": items})

    # Prefer lang blocks: english-detail-ff + urdu-detail-ff
    eng_chunk = extract_lang_block(html, "english-detail-ff") or dir_html
    urd_chunk = extract_lang_block(html, "urdu-detail-ff")
    english = paras_from(eng_chunk)
    # Drop ingredient-looking lead-ins from eng directions if Ingredients: leaked
    english = [e for e in english if not e.lower().startswith("ingredients")]
    urdu = paras_from(urd_chunk) if urd_chunk else []
    steps = pair_steps(english, urdu)

    # og / excerpt helpers
    og = re.search(r'property="og:image"\s+content="([^"]+)"', html)
    desc = re.search(r'property="og:description"\s+content="([^"]+)"', html)
    return {
        "ingredientGroups": groups,
        "steps": steps,
        "ogImage": og.group(1) if og else None,
        "ogDescription": unescape(desc.group(1)) if desc else None,
    }


def fetch_catalog(force: bool = False) -> list[dict]:
    OUT.mkdir(parents=True, exist_ok=True)
    catalog_path = OUT / "catalog.json"
    if catalog_path.exists() and not force:
        print(f"catalog cache hit: {catalog_path}")
        return json.loads(catalog_path.read_text(encoding="utf-8"))

    # discover total pages
    _, headers = http_get(f"{API}?per_page=1&page=1&_fields=id")
    total = int(headers.get("x-wp-total", "0"))
    pages = int(headers.get("x-wp-totalpages", "0"))
    # with per_page=100
    pages = max(1, (total + PER_PAGE - 1) // PER_PAGE)
    print(f"FoodFusion catalog: {total} recipes, {pages} pages @ {PER_PAGE}")

    rows: list[dict] = []
    for page in range(1, pages + 1):
        url = f"{API}?per_page={PER_PAGE}&page={page}&_embed=1"
        raw, _ = http_get(url)
        batch = json.loads(raw.decode("utf-8"))
        for p in batch:
            title = strip_tags(p.get("title", {}).get("rendered", ""))
            excerpt = strip_tags(p.get("excerpt", {}).get("rendered", ""))
            classes = p.get("class_list") or []
            media = None
            emb = (p.get("_embedded") or {}).get("wp:featuredmedia") or []
            if emb:
                media = emb[0].get("source_url") or emb[0].get("media_details", {}).get("sizes", {}).get(
                    "full", {}
                ).get("source_url")
            rid = slug_id(p["slug"])
            rows.append(
                {
                    "wpId": p["id"],
                    "slug": p["slug"],
                    "id": rid,
                    "title": title,
                    "excerpt": excerpt,
                    "link": p.get("link"),
                    "date": p.get("date"),
                    "modified": p.get("modified"),
                    "classList": classes,
                    "chapter": map_chapter(classes, title),
                    "imageUrl": media,
                    "source": "foodfusion",
                    "attribution": "Recipe adapted from Food Fusion (foodfusion.com). Not an official Food Fusion product.",
                }
            )
        print(f"  page {page}/{pages} (+{len(batch)}) total={len(rows)}")
        time.sleep(0.25)

    catalog_path.write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")
    (OUT / "catalog.meta.json").write_text(
        json.dumps({"total": len(rows), "fetchedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}, indent=2),
        encoding="utf-8",
    )
    return rows


def fetch_bodies(catalog: list[dict], limit: int | None) -> dict[str, dict]:
    bodies_dir = OUT / "recipes"
    bodies_dir.mkdir(parents=True, exist_ok=True)
    # Prefer classics / chapter diversity: sort by chapter then title
    work = list(catalog)
    if limit is not None:
        # prioritize: has image, desi-ish chapters, short slug (often classics)
        work = sorted(
            work,
            key=lambda r: (
                0 if r.get("imageUrl") else 1,
                0 if r["chapter"] in ("pakistani", "desserts", "breads", "snacks") else 1,
                len(r["slug"]),
                r["title"],
            ),
        )[:limit]

    out: dict[str, dict] = {}
    work = [r for r in work if not is_junk_row(r)]
    for i, row in enumerate(work, 1):
        path = bodies_dir / f"{row['id']}.json"
        if path.exists():
            out[row["id"]] = json.loads(path.read_text(encoding="utf-8"))
            continue
        link = row.get("link")
        if not link:
            continue
        try:
            raw, _ = http_get(link)
            html = raw.decode("utf-8", errors="ignore")
            parsed = parse_body(html)
            rec = {**row, **parsed, "scrapedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
            path.write_text(json.dumps(rec, indent=2, ensure_ascii=False), encoding="utf-8")
            out[row["id"]] = rec
            n_ing = sum(len(g["items"]) for g in parsed["ingredientGroups"])
            print(f"  [{i}/{len(work)}] {row['id']} ings={n_ing} steps={len(parsed['steps'])}")
        except Exception as e:  # noqa: BLE001
            print(f"  [{i}/{len(work)}] FAIL {row['id']}: {e}")
        time.sleep(0.35)
    return out


